create extension if not exists pgcrypto;

-- =========================================================
-- ENUMS
-- =========================================================

do $$ begin
  create type public.user_role as enum ('VISITOR', 'REPORTER', 'EXPORTER', 'ADMIN');
exception when duplicate_object then null;
end $$;

do $$ begin
  create type public.verification_status as enum ('PENDING', 'VERIFIED', 'REJECTED');
exception when duplicate_object then null;
end $$;

do $$ begin
  create type public.subscription_status as enum ('ACTIVE', 'EXPIRED', 'PENDING_PAYMENT', 'SUSPENDED');
exception when duplicate_object then null;
end $$;

do $$ begin
  create type public.rfq_status as enum ('OPEN', 'CLOSED', 'AWARDED', 'CANCELLED');
exception when duplicate_object then null;
end $$;

do $$ begin
  create type public.quote_status as enum ('PENDING', 'ACCEPTED', 'REJECTED', 'EXPIRED');
exception when duplicate_object then null;
end $$;

do $$ begin
  create type public.listing_type as enum ('LOCAL_SUPPLIER', 'DISTRESSED_CARGO');
exception when duplicate_object then null;
end $$;

-- =========================================================
-- 1. PROFILES
-- =========================================================

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  user_role public.user_role not null default 'VISITOR',
  full_name varchar(255),
  company_name varchar(255),
  country_code varchar(3), -- ISO alpha-3
  business_phone varchar(50),
  whatsapp_number varchar(50),
  is_verified boolean not null default false,
  profile_browsing boolean not null default true,
  created_at timestamptz not null default now()
);

-- =========================================================
-- 2. SUBSCRIPTION PLANS
-- =========================================================

create table if not exists public.subscription_plans (
  subscription_code varchar(50) primary key,
  name_en varchar(255) not null,
  name_ar varchar(255),
  annual_price_usd numeric(12,2),
  annual_price_usd_discounted numeric(12,2),
  max_products integer,
  max_storage_mb integer,
  video_allowed boolean not null default false,
  max_video_duration_minutes integer,
  monthly_frequency_days integer
);

-- =========================================================
-- 3. SUBSCRIPTIONS
-- =========================================================

create table if not exists public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null,
  subscription_code varchar(50) not null
    references public.subscription_plans(subscription_code),
  subscription_status public.subscription_status not null default 'PENDING_PAYMENT',
  billing_cycle_start timestamptz,
  billing_cycle_end timestamptz,
  payment_method varchar(100),
  payment_reference varchar(255),
  amount numeric(12,2),
  currency varchar(10) not null default 'USD',
  tax text,
  billing_document_url text,
  subscribed_by uuid references public.profiles(id),
  approved_at timestamptz,
  payment_notes text
);

-- =========================================================
-- 4. CATEGORIES
-- =========================================================

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  parent_id bigint references public.categories(id) on delete set null,
  code varchar(100) unique,
  name_en varchar(255) not null,
  name_ar varchar(255),
  hs_code varchar(50),
  display_order integer not null default 0
);

-- =========================================================
-- 5. COMPANIES
-- =========================================================

create table if not exists public.companies (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  company_name_en varchar(255) not null,
  company_name_ar varchar(255),
  slug varchar(255) unique not null,
  cr_number varchar(100) unique, -- Commercial Registration
  tax_id varchar(100) unique,
  governorate varchar(255),
  factory_address_ar text,
  factory_address_en text,
  company_phone varchar(50),
  website varchar(500),
  company_email varchar(320),
  cr_document_url text,
  verification_status public.verification_status not null default 'PENDING',
  verified_at timestamptz,
  verified_by uuid references public.profiles(id) on delete set null,
  logo_url text,
  cover_banner_url text,
  about_ar text,
  about_en text,
  quality_iso varchar(255),
  annual_capacity_ml numeric,
  export_port_history text,
  youtube_video_id varchar(100),
  featured_gallery_url text,
  sorting_machinery text,
  cold_storage_capacity_ml numeric,
  featured_gallery_url_2 text,
  created_at timestamptz not null default now()
);

-- =========================================================
-- 6. PRODUCTS
-- =========================================================

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  category_id bigint references public.categories(id) on delete set null,
  title_ar varchar(255),
  title_en varchar(255),
  slug varchar(255) unique,
  body_ar text,
  body_en text,
  hs_code varchar(50),
  packaging_type varchar(255),
  harvest_season_from varchar(20),
  harvest_season_to varchar(20),
  price numeric(12,2),
  minimum_order_quantity numeric,
  is_published boolean not null default false,
  published_at timestamptz
);

-- =========================================================
-- 7. COMPANY CERTIFICATES
-- =========================================================

create table if not exists public.company_certificates (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  certificate_name varchar(255),
  certificate_number varchar(255),
  valid_from date,
  valid_to date,
  document_url text,
  verification_status public.verification_status not null default 'PENDING',
  issued_by uuid references public.profiles(id) on delete set null
);

-- =========================================================
-- 8. RFQs
-- =========================================================

create table if not exists public.rfqs (
  id uuid primary key default gen_random_uuid(),
  requester_id uuid not null references public.profiles(id) on delete cascade,
  category_id bigint references public.categories(id) on delete set null,
  required_quantity numeric not null,
  quantity_unit varchar(100),
  destination_country_code varchar(3),
  destination_port varchar(255),
  incoterm varchar(50),
  delivery_deadline date,
  quote_deadline timestamptz,
  technical_specifications text,
  packaging_requirements text,
  payment_terms varchar(255),
  rfq_status public.rfq_status not null default 'OPEN',
  created_at timestamptz not null default now()
);

-- =========================================================
-- 9. QUOTES
-- =========================================================

create table if not exists public.quotes (
  id uuid primary key default gen_random_uuid(),
  rfq_id uuid not null references public.rfqs(id) on delete cascade,
  company_id uuid not null references public.companies(id) on delete cascade,
  unit_price numeric(12,2),
  currency varchar(10) not null default 'USD',
  port_of_loading varchar(255),
  lead_time_days integer,
  valid_until date,
  commercial_terms text,
  packaging_details text,
  delivery_terms text,
  status public.quote_status not null default 'PENDING',
  submitted_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- =========================================================
