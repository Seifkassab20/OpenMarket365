  currency varchar(10) not null default 'USD',
  quantity numeric,
  quantity_unit varchar(100),
  location varchar(255),
  description_country_code varchar(3),
  bill_of_lading_number varchar(255),
  quality_grade varchar(100),
  seller_contact_phone varchar(50),
  seller_contact_email varchar(320),
  image_url text,
  document_url text,
